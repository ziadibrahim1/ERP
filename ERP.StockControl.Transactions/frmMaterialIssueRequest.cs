		//IL_0245: Expected O, but got Unknown
		Main.StartBulkTrans(FromServer: false);
		try
		{
			int num = MaterialIssueRequest.Insert_Update("-1", ((Control)(object)txtCode).Text, dtpDate.DateTime.ToString(GlobalVariables.DateLongFormate), ((TextEditorControlBase)cboDepartment).Value.ToString(), ((Control)(object)txtNotes).Text, "0", "0", "0", "0", GlobalVariables.CurrentBranchID, GlobalVariables.UserID);
