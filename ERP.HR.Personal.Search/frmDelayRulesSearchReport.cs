public class frmDelayRulesSearchReport : frmSearchReport
{
	private IContainer components = null;

	public frmDelayRulesSearchReport()
	{
		InitializeComponent();
	}

	public frmDelayRulesSearchReport(DataTable dt, string idColumnName)
		: this()
	{
		dtSource = dt;
		IDColumn = idColumnName;
	}

	public override void InitGrid()
	{
		base.InitGrid();
		((UltraGridBase)ULGData).DisplayLayout.Override.AllowDelete = (DefaultableBoolean)2;
		((UltraGridBase)ULGData).DisplayLayout.Bands[0].Columns["DelayRuleNo"].Hidden = false;
		((HeaderBase)((UltraGridBase)ULGData).DisplayLayout.Bands[0].Columns["DelayRuleNo"].Header).Caption = (GlobalVariables.IsArabic ? "رقم" : "No");
