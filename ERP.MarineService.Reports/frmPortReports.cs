	public override void FormLoad()
	{
		base.FormLoad();
		((UltraToggleEditorBase)chkAll).Checked = false;
		dtCompanies = Companies.FillCombo(GlobalVariables.IsArabic ? "1" : "0", IsFromServer: false);
		GlobalFunctions.FillCombo(cboCompanies, dtCompanies, "CompanyID", "CompanyName");
	}

	public override void FillData()
	{
		GetBranches();
		Items = TreeFunctions.GetTreeCheckedNodesIDs(TreeItems);
		dtItems = Operations.FillRepTree(Branches, dtpFromDate.DateTime.Date.ToString(GlobalVariables.DateShortFormate), dtpToDate.DateTime.ToString("MM/dd/yyyy 23:59:59"), GlobalVariables.IsArabic ? "1" : "0");
		if (dtItems != null)
		{
			TreeFunctions.FillTreeOneLevel(TreeItems, dtItems, TreeItemsIDCol, TreeItemsNameCol);
		}
	}

	public override string GetReportName()
	{
		return GlobalVariables.ReportsPath + (((UltraToggleEditorBase)chkIsArabic).Checked ? "Rep_MS_OperationServices.rpt" : "Rep_MS_OperationServices.rpt");
	}

	public override void ShowReport()
	{
		if (cboCompanies.SelectedIndex == -1)
		{
			GlobalVariables.InformationMB.Show(GlobalVariables.IsArabic ? "برجاء إختيار الشركة" : "Please Select Company");
			((TextEditorControlBase)cboCompanies).Focus();
			cboCompanies.DropDown();
			return;
		}
		GetItems();
		if (Items.Equals(","))
		{
			GlobalVariables.InformationMB.Show("لم تقم باختيار اى عملية ليتم عرضها ", "There is no chosen Operation to be shown in the report.");
			return;
		}
		frmReporViwer frmReporViwer2 = new frmReporViwer();
		GlobalVariables.ReportDocument.SetParameterValue("@OperationIDs", Items);
		GlobalVariables.ReportDocument.SetParameterValue("@CompanyID", int.Parse(((TextEditorControlBase)cboCompanies).Value.ToString()));
		frmReporViwer2.Tag = base.Tag;
		frmReporViwer2.MdiParent = base.MdiParent;
		frmReporViwer2.TopLevel = false;
		frmReporViwer2.Parent = base.Parent;
		frmReporViwer2.Width = base.Parent.Width;
		frmReporViwer2.Height = base.Parent.Height;
		frmReporViwer2.frmParent = this;
		frmReporViwer2.Show();
		frmReporViwer2.BringToFront();
	}

